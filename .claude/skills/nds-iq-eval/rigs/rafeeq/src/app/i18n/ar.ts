const daysWord = (n: number): string =>
  n === 1 ? 'يوم واحد' : n === 2 ? 'يومان' : n <= 10 ? `${n} أيام` : `${n} يومًا`;

const daysAfter = (n: number): string =>
  n === 2 ? 'يومين' : daysWord(n);

